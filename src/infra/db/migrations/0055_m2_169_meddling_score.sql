-- M2.169 修正：**一场陨落只认一个首功**。
--
-- 起因（用户提问）：「但是有多位玩家参与了怎么算？」
--
-- 原来的实现是 `COUNT(DISTINCT scheme_id)` —— **人人有份**：
-- 十个玩家在同一场阴谋上各伸一次手，那一局成了之后，十个人全都拿到
-- 「参与导致神陨落」的资格。而序列 0 是**唯一**的（一条途径只有一个位置）——
-- 那等于批量生产成神资格。
--
-- 现在把「分量」在**插手那一刻**算好并冻结在这一列里（不依赖序列后来变没变），
-- 结算时按分排名，只有第一名算「首功」。
ALTER TABLE divine_meddling ADD COLUMN score INTEGER NOT NULL DEFAULT 0;
