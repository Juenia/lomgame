-- M2.69：事件卡的**每日上限**（`daily_limit`）接判定。
--
-- ## 这一列补的是哪个洞
--
-- `daily_limit` 从 W2 起就写在每一张卡的顶层（65 张全有），
-- 而运行期**一个字节都没读过** —— 每日去重走的是「(角色, 卡, 日期) 一行」的存在性，
-- 也就是**恒为 1 次**。于是：
--
--   · 写 `daily_limit: 2` 的两张卡（daily_012 / daily_016）实际只能触发一次；
--   · `daily_limit: 0` 没有任何办法表达「今天不要出这张卡」。
--
-- ⇒ 一行记录从「触发过没有」变成「触发过几次」。
--
-- ## 兼容性
--
-- `ADD COLUMN ... DEFAULT 1`：老库里的每一行（触发过的那一次）读出来是 1，
-- 与加这一列之前**逐位相同**（limit 1 的卡照样一天一次）。
-- 新库由 0002 建表、这一条补列，两条路径的终点一致。
-- =====================================================================

ALTER TABLE event_triggers ADD COLUMN count INTEGER NOT NULL DEFAULT 1;
