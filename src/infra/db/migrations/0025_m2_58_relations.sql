-- M2.58：物种模板的生态关系网（creatures.yaml 的 relations 段）。
--
-- 为什么要在库里存一份：creature_species 是「内容在库里的运行时副本」，
-- 与 items / locations 不同（那两张是纯内容，判定层直接读内存表），
-- 物种表被 creatures（世界状态）外键引用，报告与审计要能回答「当时它是什么物种」。
-- 关系网是物种的一部分，所以它跟 habitat_json / drops_json 一样落库 ——
-- 否则「这只骨语者当时吃得到谁」在内容表改过之后就再也复现不出来。
--
-- ⚠️ 列**必须可空**：
--   1. 既有库里的行没有这一列的值，加 NOT NULL 会让迁移在已有数据上直接失败；
--   2. 测试里有一处手写 INSERT 不列这一列（test/admin-panels.test.ts），
--      可空 = 那处 INSERT 继续工作，读侧对 NULL 有兜底（undefined = 没有声明关系）。
-- 这与 relations 段本身是可选的是同一条口径：不写就不写，读侧落回旧行为。
--
-- 为什么不改 0017_m2_8.sql 的建表语句：它已经在既有库上应用过，
-- schema_migrations 里那条记录不会重跑，改文件只对新库生效 ——
-- 结果是「老库没有列、新库有列」，本地能跑、别人拉起来就错。
-- =====================================================================

ALTER TABLE creature_species ADD COLUMN relations_json TEXT;
