-- =====================================================================
-- M2.58 阶段三：生态域的**运行时状态**（信息生态的落点）。
--
-- 为什么要和 zones.yaml 分开：
--   zones.yaml         —— 内容。一个地方的世界脾气（灵性、污染、承载力…），静态。
--   zone_state（本表） —— 世界状态。它**会因为发生了什么而改变**。
-- 这两者在项目里一直是分开的（items/locations 是内容，characters/creatures 是状态），
-- 生态域不该是例外。
--
-- 本表目前存两个东西：
--   fear            恐慌度 0—1：目击累积、随时间衰减。
--   sighting_count  目击计数：用来算「这个地方最近出了多少事」。
--
-- ⚠️ 为什么恐慌要能累积，而不是只写在 zones.yaml 里：
--   阶段二的域参数是**静态**的 —— 一个地方的世界脾气固定不变，
--   玩家做什么都不会改变它。阶段三要修的正是这件事：
--   目击 → 谣言 → 恐慌 → 生态被压住，这条链的第一环需要一个可变的落点。
--
-- ⚠️ 恐慌**不是** zones.yaml 里的 fear 的副本：
--   那是这个域的**基线气质**（内容），这里是**此刻实际有多少**（状态）。
--   两者在读取时相加后 clamp 到 1（见 domain/world/zone.ts 的 fearLevelOf）。
-- =====================================================================

CREATE TABLE IF NOT EXISTS zone_state (
  zone_id         TEXT PRIMARY KEY,
  -- 恐慌度 0—1：目击累积、随小时衰减
  fear            REAL NOT NULL DEFAULT 0,
  -- 累计目击次数（只增不减；报告与审计读它）
  sighting_count  INTEGER NOT NULL DEFAULT 0,
  -- 最后一次目击的时刻（毫秒）
  last_sighting_at INTEGER,
  updated_at      INTEGER NOT NULL
);

-- 恐慌累积与衰减都是每小时一次的全表小更新，这张表最多 6 行（一个域一行），
-- 所以不需要额外索引。
