-- M2.170 续：**对撞** —— 两个人同时争同一个位置。
--
-- 上一版的行为是「先到先得」：有人已经在上面了，后来者只能去**打断**他（杀人）。
-- 但那只覆盖了一半 —— 后来者可以说「我也上去」，于是两个人同时在灰雾之上，
-- 而那个位置**只坐得下一个**。
--
-- 对撞的规则（残酷且明确）：
--   · 两个人一起争 ⇒ 仪式**更久**（那个位置只有一份，谁也别想干净地下来）
--   · 侵蚀**加倍**（神性只有一份，两个人在抢它 —— 争神位的人可能先变成怪物）
--   · 到期时若还有别人在争 ⇒ **谁都不算数**，时间表往后拖（最多拖 3 次）
--   · 拖满 3 次 ⇒ 两个人都下来，位置继续空着（**两败俱伤**）
--
-- ⚠️ 唯一的出路是把对方逼死或逼退 —— 这不是抢分，这是相杀。
