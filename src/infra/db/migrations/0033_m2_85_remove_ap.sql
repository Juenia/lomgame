-- M2.85：**行动值（AP）机制整体移除** —— characters.ap 列下线。
--
-- ## 为什么删列，而不是「留着不用」
--
-- 行动值在 M2.85 被砍掉（原设计每天 5 点 = 玩家一天只能玩 5 次，对异步文字游戏是致命限制）。
-- 随它一起消失的是：探索 / 移动 / 事件 / 休息 / 净化 / 袭击 / 干扰 / 举报 /
-- 对峙 / 撤退的消耗、每日 tick 的恢复、通缉的「行动点效率」惩罚、
-- PVP 僵持与战败的扣点、时间沙漏的效果。
--
-- 留一个再也没有读写方的列，下一个人读到它只会重新问一遍「这个字段还有人用吗」——
-- 而且它会随 dump 与报告继续出现在读数里（K19 的形状：看起来还在，其实已经死了）。
--
-- ## 两条边界
--
-- 1. 历史迁移（0001 / 0016）里的 `ap` **不动**：那是当时的 schema 快照。
--    改了会让「从零重放迁移」与「已在跑的库」走上两条不同的历史。
-- 2. SQLite（3.35+；node:sqlite 内置版本远高于此）的 DROP COLUMN 有前置条件：
--    该列不能有索引、不能被唯一约束或主键引用。ap 三条全不沾，可以直接删。
ALTER TABLE characters DROP COLUMN ap;
