/** 序列取值：9 最低、0 最高（与 CharacterState.sequence 同一口径） */
export const ALL_SEQUENCES: readonly number[] = [9, 8, 7, 6, 5, 4, 3, 2, 1, 0];

/**
 * 本版**玩家可达**的最高序列（= CONTENT_TARGET_SEQ − 1）。
 *
 * 本地重写而不是 import `config/content-scope.ts`：卡面是纯展示层，
 * 不该把「内容做到哪一层」这种会被批次推进的数字拖进来。边界只用于**标注**。
 */
export const PLAYER_REACHABLE_SEQUENCE = 2;

/** 这一档本版能不能玩到（0/1 只能看，不能升上去） */
export function playableSequence(sequence: number): boolean {
  return sequence >= PLAYER_REACHABLE_SEQUENCE;
}

/**
 * 取一个称号。
 *
 * **缺失即抛**（与 `lossOfControlThresholdFor` 同一条纪律 K19）：不回退到
 * 「序列 N」这种占位串 —— 那会把「这张表漏了一档」变成卡面上一句看不出错的废话。
 */
export function sequenceTitle(pathway: PathwayId, sequence: number): string {
  const row = SEQUENCE_TITLES[pathway];
  if (row === undefined) throw new Error(`SEQUENCE_TITLES 里没有途径 "${pathway}"`);
  const title = row[sequence];
  if (title === undefined) {
    throw new Error(`SEQUENCE_TITLES 里没有 ${pathway} 的序列 ${sequence} 的称号 —— 不隐含占位名（K19）`);
  }
  return title;
}

/** 遍历全部 (途径 × 序列) 组合 —— 卡面批量出图的唯一入口 */
export function allPathwaySequences(): ReadonlyArray<{ pathway: PathwayId; sequence: number }> {
  const out: Array<{ pathway: PathwayId; sequence: number }> = [];
  for (const pathway of ALL_PATHWAYS) {
    for (const sequence of ALL_SEQUENCES) out.push({ pathway, sequence });
  }
  return out;
}
