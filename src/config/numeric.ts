/**
 * 运行期覆盖（**只给 W5 模拟器调参用**，生产环境永远不调用）。
 * 纯函数仍然只读 NUMERIC，所以模拟器跑的是真实规则，只是把旋钮临时拧到别的值。
 */
const NUMERIC_SNAPSHOT = structuredClone(NUMERIC);

function deepMerge(target: Record<string, unknown>, patch: Record<string, unknown>): void {
  for (const [key, value] of Object.entries(patch)) {
    const current = target[key];
    if (value && typeof value === 'object' && !Array.isArray(value) && current && typeof current === 'object') {
      deepMerge(current as Record<string, unknown>, value as Record<string, unknown>);
      continue;
    }
    target[key] = value;
  }
}

export function applyNumericOverrides(patch: Record<string, unknown>): void {
  deepMerge(NUMERIC as unknown as Record<string, unknown>, patch);
}

export function resetNumeric(): void {
  deepMerge(NUMERIC as unknown as Record<string, unknown>, structuredClone(NUMERIC_SNAPSHOT));
}

/** 掉落权重的稀有度分档，纯查询函数（分档由 W5 定） */
export function rarityLabel(weight: number): string {
  for (const band of NUMERIC.drop.rarityBands) {
    if (weight <= band.maxWeight) return band.label;
  }
  return '常见';
}
