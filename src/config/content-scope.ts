/**
 * M2.35 任务 1：**本版内容覆盖范围的唯一出处（K22）**。
 *
 * ## 它回答什么问题
 *
 * 「序列 9—0 的配方齐不齐」这句话在**没有目标**的时候无法回答：
 * 序列 4—0 的配方本来就属于批次 B/C，缺它们是**计划**而不是缺陷；
 * 而序列 9—5 之间缺一层（M2.32 的 seq 7 就是现场）是**缺陷**。
 *
 * ⇒ 两者必须能被区分开，所以「内容做到哪一层」要有一个显式落点。
 *
 * ## 为什么不用「从内容表自己推」
 *
 * 也考虑过拿 `min(现有配方的 seq)` 当目标（让内容表自我声明）。它挡得住
 * 「某一条途径漏了一层」，却挡不住「**所有**途径一起漏了一层」——
 * 那种情况下内容表会把缺口读成目标，检查器静默通过（K14：抓不住故障的判据是装饰）。
 * ⇒ 目标必须**独立于被检查的对象**写出来，这是判定器与判定对象分离的老规矩。
 *
 * ## ⚠️ 改它的时机
 *
 * 批次 B（序列 4、3）落地时把它改成 `3`（M2.39），批次 C 的上半（序列 2）推到 `2`（M2.43）。
 * 改它的**同一步**是补配方 —— 否则 `loadContent()` 立刻报 error、服务端起不来
 * （那正是我们要的：**内容缺一层不该等到跑批才发现**）。
 */

/**
 * 配方覆盖的序列下限：`2` = 序列 9—2 的配方齐全，1—0 属于批次 C 的下半（M2.43 由 3 推到 2）。
 *
 * ⚠️ 它与 G12 是配套的：`CONTENT_TARGET_SEQ = 2` + 7 途径 × 8 档 = **56** 条配方。
 * 只改一个不改另一个，`loadContent()` 会立刻报 error（那正是我们要的：
 * 「内容缺一层」不该等到跑批才发现）。
 */
export const CONTENT_TARGET_SEQ = 2;

/**
 * 本版玩家**可到达的最高序列** = 内容目标 − 1。
 *
 * 依据：配方的 `seq` 是**晋升前**的序列（`promote.ts` 按 `c.seq === character.sequence` 取配方），
 * 所以有 `seq = 5` 的配方 ⇒ 序列 5 的玩家能升到 **4**。
 *
 * ⚠️ 别把这两个数读混：**内容是「做到 seq 5」，可达是「序列 4」**。
 * M2.29 那句话「序列 6/5 的内容做完了跑批够不到」说的是**配方 seq 6/5 这两层**。
 */
export const CONTENT_MAX_SEQUENCE = CONTENT_TARGET_SEQ - 1;
