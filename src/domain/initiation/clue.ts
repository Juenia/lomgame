/** 拿到线索时的那句话（不带地点名 —— 地点名由命令层补进回执） */
export function clueNarrative(pathway: PathwayId): string {
  return CLUE_TEXT[pathway];
}

/**
 * 掷一次线索。
 *
 * 概率来自 INITIATION.clueChance（5%），**逐次探索独立判定** ——
 * 不是「每天一次」，因为玩家一天可以探索好几个地点，探索得越多越可能翻到东西。
 *
 * 途径由城市势力权重决定（pickGuidedFaction）：
 * 你在一座城市里翻到的东西，自然是这座城市里流传的东西。
 */
export function rollRecipeClue(input: {
  factions: readonly GuidedFaction[];
  rng: { next(): number };
  now: number;
  /** 覆盖概率（测试与模拟器用；生产不传，读配置） */
  chance?: number;
}): { found: boolean; roll: number; chance: number; clue: RecipeClueDraft | null } {
  const chance = input.chance ?? INITIATION.clueChance;
  const roll = input.rng.next();
  if (roll >= chance) return { found: false, roll, chance, clue: null };
  const faction = pickGuidedFaction(input.factions, input.rng);
  if (!faction) return { found: false, roll, chance, clue: null };
  return {
    found: true,
    roll,
    chance,
    clue: {
      pathway: faction.pathway,
      clueText: CLUE_TEXT[faction.pathway],
      foundAt: input.now,
    },
  };
}
